generate_packer() {
  local out="$PACKER_PKRVARS/packer.pkrvars.template"
  log "Generating packer variable template..."

  cat > "$out" <<'EOF'
# This map contains vars that are used in packer templates
# Generated by scripts/generate-vars.sh
# Copy to /packer/packer.pkrvars and populate with real data

env = {
  proxmox_url="http://192.168.x.x:8006/api2/json"
  proxmox_user="user"
  proxmox_password="password"
  proxmox_node="node"
