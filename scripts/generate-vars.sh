}
EOF

  log "Wrote $out"
}

# ─── Main ────────────────────────────────────────────────────────────────────

echo "Generating tfvars templates from project..."
echo ""

generate_nomad_jobs
generate_storage
generate_env
generate_cluster
generate_packer

echo ""
echo "Done. Templates written to:"
echo "  $SERVICES_TFVARS/"
echo "  $CLUSTER_TFVARS/"
echo "  $PACKER_PKRVARS/"
echo ""
echo "Review the generated files, fill in placeholder values, then copy"
echo "them to their parent directories as .auto.tfvars files."
